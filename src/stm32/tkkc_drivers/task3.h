#ifndef __TASK3_H
#define __TASK3_H

/* 任务3: 十次抓取确认前使用任务1式手势控制
 *        -> 连续十次抓取后锁定舵机在抓取状态
 *        -> 锁爪后电机继续随手势运动
 *        -> 进入小任务前连续十次松开可解锁并恢复手势控制
 *        -> 识别到非0手指后静默100ms, 再用新帧识别
 *        -> 不判断开合状态, 非2跳变到2后连续十次2指 -> 小任务1
 *        -> 不判断开合状态, 非3跳变到3后连续十次3指 -> 小任务2
 *        -> 两个小任务: 电机2/4同时反转一圈 -> 电机1/3首段动作
 *        -> 小任务1: 电机1/3正转 -> 电机2/4正转 -> 夹爪松开
 *          -> 电机2/4反转 -> 电机1/3反转 -> 电机2/4正转
 *        -> 小任务2: 电机1/3反转 -> 电机2/4正转 -> 夹爪松开
 *          -> 电机2/4反转 -> 电机1/3正转 -> 电机2/4正转
 *        -> 全部停止 -> 恢复手势跟随 -> 重新识别触发指令。 */
void Task3_Enter(void);
void Task3_Step(void);
void Task3_Exit(void);

#endif /* __TASK3_H */
