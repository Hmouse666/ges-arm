#ifndef __MOTOR_H
#define __MOTOR_H
#include "stm32f1xx_hal.h"

/* ==========================================================================
 * 步进电机驱动(软件发脉冲, 不用定时器) —— 从 test3 工程移植过来的
 *
 * 接线方式(和原来一样): 控制端是"共地"接法
 *      PUL- / DIR- / EN-  -> 全部接地
 *      PUL+ / DIR+ / EN+  -> 接单片机的 IO
 *      电源+ -> 24V,  电源- -> 地
 *   所以单片机输出高电平 = 该路信号有效。
 *
 * ★★★ 引脚就是 test3 那一套(因为你已经按 test3 接好了线) ★★★
 *
 *     电机    | PUL  | DIR  | EN   | 这几个脚在本工程里同时还连着别的东西
 *    ---------|------|------|------|------------------------------------------------
 *     电机1   | PA0  | PA1  | PA2  | PA0/PA1 是板上的按键2 / 按键3
 *     电机2   | PB0  | PB1  | PA3  | PA3 是液晶屏的 CS  ★这个是真的抢不过来
 *     电机3   | PB6  | PB8  | PB9  | PB6/PB8/PB9 是 LED5 / LED7 / LED8
 *     电机4   | PA12 | PB3  | PB5  | PB3/PB5 是 LED2 / LED4
 *
 *   ★★ 注意: 上面 电机3 / 电机4 两行是【把引脚互换以后】的样子 ★★
 *      电机3 -> PUL=PB6  DIR=PB8  EN=PB9   (原来是电机4 的那三根)
 *      电机4 -> PUL=PA12 DIR=PB3  EN=PB5   (原来是电机3 的那三根)
 *      只换了引脚, 电机号(3 和 4)本身没变; 程序里还是用 MOTOR_3 / MOTOR_4 称呼它们。
 *      和原来(没换之前)的区别只有下面"① 引脚配置"那几行。
 *
 *   为了不让"同一个脚上的两个功能"打架, 本工程里已经做了下面这些让步:
 *      1) PA0 / PA1 : 从按键表里删掉了(key.c 现在只剩 PC14/PC13/PC15 三个按键),
 *                     "反转"按键改成 PC13(原来的 KEY_4); PA0/PA1 上的两个板载按键
 *                     就别再按了 —— 按下去等于把电机1的脉冲/方向线拉到地。
 *      2) PB3       : 反转按键的指示灯从 LED2 改成 LED3(PB4), 这样没人再去写 PB3
 *                     (LED2 这个灯就用不了了)。
 *      3) PB5 / PB6 : Led_Init() 之后 Motor_Init() 会把它们重新配成输出(电机赢),
 *                     程序里也从来没点亮过 LED4/LED5。
 *      4) PB8 / PB9 : 本来是 TIM4_CH3/CH4 的复用脚(LED7/LED8 呼吸灯), 只要不启动
 *                     PWM, Motor_Init() 覆盖掉就行 —— 代价是 LED7/LED8 呼吸灯失效。
 *      5) PA3       : ★这个在软件里让不开★ 它既是液晶屏的 CS, 又是电机2的 EN。
 *                     默认把 PA3 留给电机2, 所以屏幕就不显示了
 *                     (APP.c 里 APP_USE_LCD = 0)。
 *                     想把屏幕也用起来: 把电机2的 EN+ 从 PA3 挪到 PB12 一根线,
 *                     然后把下面"备用"那两行打开, 并把 APP.c 的 APP_USE_LCD 改成 1。
 *
 *   以后要换脚: 只改下面"① 引脚配置"里对应的几行, motor.c 一个字都不用动。
 *
 * 两种用法:
 *   1) 一次只转一个电机:  Motor_Run(电机号, 圈数, 方向, 脉冲间隔)
 *   2) 几个电机"同时"转:  Motor_RunSync(选中哪几个, 圈数, 方向, 脉冲间隔)
 *
 * 两个函数都是"阻塞"的 —— 把脉冲全部发完才返回, 期间干不了别的事。
 * ========================================================================== */

/* ==========================================================================
 * ① 引脚配置(改这里就能换脚)
 *    每行 = "这个功能接在哪个口的哪个脚", 端口写 GPIOA/GPIOB, 脚写 GPIO_PIN_x
 * ========================================================================== */

/* -------- 电机1: PUL=PA0  DIR=PA1  EN=PA2 --------
 * (PA0/PA1 原来还能当按键用, 现在归电机了, 见上面第 1 条) */
#define MOTOR1_PUL_PORT     GPIOA
#define MOTOR1_PUL_PIN      GPIO_PIN_0
#define MOTOR1_DIR_PORT     GPIOA
#define MOTOR1_DIR_PIN      GPIO_PIN_1
#define MOTOR1_EN_PORT      GPIOA
#define MOTOR1_EN_PIN       GPIO_PIN_2

/* -------- 电机2: PUL=PB0  DIR=PB1  EN=PA3(和屏幕CS同脚, 见上面第 5 条) -------- */
#define MOTOR2_PUL_PORT     GPIOB
#define MOTOR2_PUL_PIN      GPIO_PIN_0
#define MOTOR2_DIR_PORT     GPIOB
#define MOTOR2_DIR_PIN      GPIO_PIN_1
#define MOTOR2_EN_PORT      GPIOA
#define MOTOR2_EN_PIN       GPIO_PIN_3

/* -------- 电机3: PUL=PB6  DIR=PB8  EN=PB9 -------- */
#define MOTOR3_PUL_PORT     GPIOB
#define MOTOR3_PUL_PIN      GPIO_PIN_6
#define MOTOR3_DIR_PORT     GPIOB
#define MOTOR3_DIR_PIN      GPIO_PIN_8
#define MOTOR3_EN_PORT      GPIOB
#define MOTOR3_EN_PIN       GPIO_PIN_9

/* -------- 电机4: PUL=PA12  DIR=PB3  EN=PB5 (★ 和电机3 互换了引脚) -------- */
#define MOTOR4_PUL_PORT     GPIOA
#define MOTOR4_PUL_PIN      GPIO_PIN_12
#define MOTOR4_DIR_PORT     GPIOB
#define MOTOR4_DIR_PIN      GPIO_PIN_3
#define MOTOR4_EN_PORT      GPIOB
#define MOTOR4_EN_PIN       GPIO_PIN_5

/* --------------------------------------------------------------------------
 * 备用: 想把液晶屏也用起来(不想让屏幕一直是黑的), 只动一根线就行 ——
 *       把 电机2 的 EN+ 从 PA3 改接到 PB12, 然后把下面这两行前面的 // 去掉,
 *       同时把上面 ① 里电机2的 EN 那两行注释掉(不然会重复定义, 编译会告警)。
 *       APP.c 里再把 APP_USE_LCD 改成 1, 屏幕上就又有显示, 四个电机也都能用。
 *
 *       注意: PB12 在本工程里原来只是被 CubeMX 配成了输出, 没有任何功能用它,
 *             所以拿来做电机2的 EN 不会影响别的东西。
 * -------------------------------------------------------------------------- */
// #define MOTOR2_EN_PORT      GPIOB
// #define MOTOR2_EN_PIN       GPIO_PIN_12

/* ==========================================================================
 * ② 想改速度和圈数就改这几个数
 * ========================================================================== */

/* 转一圈需要多少个脉冲。
 * 这个数 = 电机一圈的步数 × 驱动器细分, 和驱动器上的拨码开关有关, 常见组合:
 *      步距角 1.8 度(一圈 200 步) × 细分 100 = 20000
 *      步距角 1.8 度(一圈 200 步) × 细分  50 = 10000
 *      步距角 0.9 度(一圈 400 步) × 细分  50 = 20000
 * 如果发现"转一圈"其实转多了或者转少了, 就按比例改这个数。 */
#define PULSE_PER_REV 20000

/* 默认脉冲间隔(us), 也就是两个脉冲之间等多久。这个数越大, 电机转得越慢。
 * 500us -> 脉冲频率约 2kHz -> 约 6 转/分钟(转一圈约 10 秒)。 */
#define DEFAULT_SPEED 500

/* ★ 脉冲高电平的宽度(空循环的次数, 1 次约 0.11us)。
 *
 * 这个数很关键! 驱动器输入端一般都有光耦, 光耦要"亮"够时间驱动器才认得出这一步:
 *      原 来 10 次 = 约 1.1us  -> 太窄! 很多驱动器(要求大于 2.5us)会漏掉脉冲,
 *                                 表现出来就是"量不到脉冲 / 电机完全不转";
 *      现 在 50 次 = 约 5.6us  -> 绝大多数驱动器都能可靠识别。
 * 如果换了驱动器还是不动, 可以继续加大到 100(约 11us)。
 * 注意: 这个数只影响"高电平持续多久", 不影响转速(转速由 DEFAULT_SPEED 决定)。 */
#define PULSE_HIGH_CNT 50

/* ==========================================================================
 * ③ 电机编号
 * ========================================================================== */

#define MOTOR_1     1       /* PUL=PA0   DIR=PA1   EN=PA2  */
#define MOTOR_2     2       /* PUL=PB0   DIR=PB1   EN=PA3  */
#define MOTOR_3     3       /* PUL=PB6   DIR=PB8   EN=PB9 */
#define MOTOR_4     4       /* PUL=PA12  DIR=PB3   EN=PB5  (和电机3 互换了引脚) */

/* ==========================================================================
 * ④ 同时转的时候, 用这几位置来选电机
 *    几个可以按位或起来, 例如:
 *        Motor_RunSync(MOTOR_SEL_ALL, 1.0f, 0, DEFAULT_SPEED);              // 四个一起
 *        Motor_RunSync(MOTOR_SEL_1 | MOTOR_SEL_4, 1.0f, 0, DEFAULT_SPEED);  // 只要 1 和 4
 * ========================================================================== */

#define MOTOR_SEL_1     0x01u   /* 选上电机1 */
#define MOTOR_SEL_2     0x02u   /* 选上电机2 */
#define MOTOR_SEL_3     0x08u   /* 选上电机3 */
#define MOTOR_SEL_4     0x04u   /* 选上电机4 */
#define MOTOR_SEL_ALL   (MOTOR_SEL_1 | MOTOR_SEL_2 | MOTOR_SEL_3 | MOTOR_SEL_4)  /* 四个都要 */

/* ==========================================================================
 * ⑤ 每个电机的使能电平
 *    四个电机的 EN- 都接地, EN+ 接单片机 IO, 所以 IO 输出低电平时 EN 光耦是不导通的。
 *    这里统一按"低电平使能"写。
 * ★ 如果某个电机上电后是松的(用手能拧动转轴、没有保持力矩),
 *   就把对应的那个宏改成 GPIO_PIN_SET, 重新编译烧录再试。 */
#define MOTOR1_EN_ACTIVE    GPIO_PIN_RESET
#define MOTOR2_EN_ACTIVE    GPIO_PIN_RESET
#define MOTOR3_EN_ACTIVE    GPIO_PIN_RESET
#define MOTOR4_EN_ACTIVE    GPIO_PIN_RESET

/* ==========================================================================
 * ⑥ 每个电机的方向要不要反过来(电机装反了 / DIR 线接反了, 不用拆线, 改这里)
 *
 *    某个电机要求它"正转"的时候实际是反着转的, 就把它的这个宏改成 1:
 *        0 = 不反(默认)          1 = 反过来
 *
 *    ★ 现在 电机4 的方向是反的, 所以 MOTOR4_DIR_INVERT 填的是 1。
 *      以后发现哪个电机反了, 把它的 0 改成 1 就行; 想改回来就把 1 改回 0。
 *
 *    这里只改 DIR 方向脚的电平, 不影响转速和脉冲个数, 改完不用动别的代码;
 *    正转和反转会一起反过来, 所以"正转再反转回到原位"照样成立。
 * ========================================================================== */

#define MOTOR1_DIR_INVERT   0       /* 电机1: 0 = 正常, 1 = 方向反过来 */
#define MOTOR2_DIR_INVERT   0       /* 电机2 */
#define MOTOR3_DIR_INVERT   0       /* 电机3 */
#define MOTOR4_DIR_INVERT   1       /* 电机4: ★装反了, 所以这里是 1 */

/* ==========================================================================
 * ⑦ 接口函数
 * ========================================================================== */

/* 上电初始化: 把 12 个脚都配成推挽输出, 并默认使能四个电机 */
void Motor_Init(void);

/* 只让一个电机转 rev 圈
 *   motor : MOTOR_1 / MOTOR_2 / MOTOR_3 / MOTOR_4
 *   rev   : 圈数, 可以填小数(0.5f = 半圈, 1.0f = 一圈)
 *   dir   : 0 = 正转, 1 = 反转(填非 0 都是反转)
 *   delay_us : 脉冲间隔(us), 越大越慢, 常用 DEFAULT_SPEED
 * 注意: 这个函数是阻塞的(脉冲发完才返回), 期间按键扫描、舵机缓动都不会执行。
 * ★ 两个电机要同时跟手时, 别用它 —— 用它发的是"一整片", 会阻塞几十毫秒,
 *   两台电机就会互相等, 顿一顿地抖。那种场合用下面的 Motor_Step()。 */
void Motor_Run(uint8_t motor, float rev, uint8_t dir, uint16_t delay_us);

/* 让选中的几个电机"同时"转 rev 圈(完全同步, 一起启动一起停)
 *   sel   : 用 MOTOR_SEL_1 ~ MOTOR_SEL_4 按位或起来
 *   其它参数和 Motor_Run() 一样
 * 注意: 几个电机同时转, 24V 电源要能供得起几倍的电流。 */
void Motor_RunSync(uint8_t sel, float rev, uint8_t dir, uint16_t delay_us);

/* ==========================================================================
 * ⑧ 发【一个】脉冲就返回(不阻塞) —— 两个电机同时跟手就用它
 *
 *   为什么要有它:
 *     Motor_Run() 是阻塞的: 它要把一整片脉冲发完才返回(几十毫秒)。
 *     只有一个电机在跟手时完全没问题; 但两个电机同时跟手时, 电机1 发脉冲的这段时间里
 *     电机4 只能干等(反过来也一样), 于是两台各自都空出一段"没有脉冲"的时间 ——
 *     看上去就是一顿一顿地抖。
 *
 *   用法: 主循环里每转一圈, 每个跟随函数各自决定"这一圈要不要发一个", 要发就调它:
 *        app_motor1_follow_x();     // 里面: 该发的时候调一次 Motor_Step(MOTOR_1, ...)
 *        app_motor4_follow_y();     //      该发的时候调一次 Motor_Step(MOTOR_4, ...)
 *     每个电机的"隔多久发一个"由各自的跟随逻辑算好(限速 + 最小间隔),
 *     所以两台电机各走各的、谁也不等谁, 同时跟手也是连续平稳的。
 *
 *   ★ 它只发一个脉冲(拉高 -> 空循环 PULSE_HIGH_CNT 次 -> 拉低), 约 6us 就返回, 不等待。
 *   ★ 同一个电机两次调用之间要留够时间(APP.c 里的 M1_SPEED_US / M4_SPEED_US), 别连着猛发。
 *   ★ 方向脚只在方向真的变了的时候才重写一次, 并多等一会儿(十几微秒)让驱动器认好方向 ——
 *     所以同一个方向连续发脉冲时, 它比 Motor_Run() 还省事(不用每次重写方向脚)。
 *   ★ Motor_Run() / Motor_RunSync() 还是原来的阻塞式, 手动测试、单轴试机照样能用。
 * ========================================================================== */

/* 发一个脉冲就返回(不阻塞)
 *   motor : MOTOR_1 / MOTOR_2 / MOTOR_3 / MOTOR_4
 *   dir   : 0 = 正转, 1 = 反转(填非 0 都是反转; 和 Motor_Run 一样会自动翻 DIR_INVERT) */
void Motor_Step(uint8_t motor, uint8_t dir);

/* 调试用: 把 12 个引脚依次慢闪(每个脚闪 3 下, 一直循环), 进去就不会出来了。
 * 因为正式程序里脉冲是 2kHz 的窄脉冲, 万用表量出来几乎是 0V, 灯珠也几乎不亮,
 * 光靠量电压分不清"是单片机没输出"还是"驱动器/接线的问题"。
 * 用这个函数就能一眼看出来: 哪个脚不闪, 就是那个脚的问题。 */
void Motor_PinTest(void);

#endif
