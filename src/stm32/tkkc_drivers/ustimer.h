#ifndef __USTIMER_H
#define __USTIMER_H

#include "main.h"

/* ==========================================================================
 * 微秒计时(DWT 周期计数器) —— 发脉冲的节拍全靠它
 *
 * 为什么要它: 一个脉冲的间隔只有几十微秒, 而 HAL_GetTick() 只有 1ms 分辨率,
 *   拿毫秒算"这一圈过了多久"根本不够细。所以用内核自带的周期计数器 DWT->CYCCNT
 *   (72MHz 下 1us = 72 个周期)。
 * ★ 只做"两个时刻相减"来算间隔, 所以计数器数满回绕(约 59 秒)也算得对。
 * ★ 万一颗芯片上 DWT 不计数, Us_Init() 会自动退回用 SysTick 凑微秒(精度差一点, 能用)。
 * ========================================================================== */

void     Us_Init(void);     /* 打开 DWT, 进主循环之前调一次 */
uint32_t Us_Now(void);      /* 当前微秒数 */

#endif /* __USTIMER_H */
